- **Patch**: $(echo "$new_version" | cut -d'.' -f3)

### Version Changes
- **Major Change**: $(echo "$new_version" | cut -d'.' -f1) → $(echo "$current_version" | cut -d'.' -f1)
- **Minor Change**: $(echo "$new_version" | cut -d'.' -f2) → $(echo "$current_version" | cut -d'.' -f2)
