#!/bin/bash

# Version Update Automation
# Automate semantic version updates across documents

set -e

echo "📈 Version Update Automation"
echo "============================"
echo ""

# Configuration
WORKFLOWS_DIR=".vibe/workflows"
VERSIONS_DIR="$WORKFLOWS_DIR/versions"
DOCS_DIR="docs"
SKILLS_DIR=".vibe/skills"

# Create versions directory
mkdir -p "$VERSIONS_DIR"

# Main function
main() {
    local command="$1"
    shift
    
    case "$command" in
        update)
            update_version "$@"
            ;;
        bump)
            bump_version "$@"
            ;;
        list)
            list_versions "$@"
            ;;
        history)
            version_history "$@"
            ;;
        *)
            show_help
            ;;
    esac
}

# Update version
update_version() {
    local document="$1"
    local new_version="$2"
    
    if [[ -z "$document" || -z "$new_version" ]]; then
        echo "Error: Document and new version required"
        echo "Usage: $0 update <document> <new_version>"
        return 1
    fi
    
    echo "Updating version for: $document"
    echo "New Version: $new_version"
    echo ""
    
    # Check if document exists
    if [[ ! -f "$document" ]]; then
        echo "❌ Document not found: $document"
        return 1
    fi
    
    # Validate version format
    if ! validate_version "$new_version"; then
        echo "❌ Invalid version format: $new_version"
        echo "Valid format: X.Y.Z (e.g., 1.0.0)"
        return 1
    fi
    
    # Extract current version
    local current_version=$(extract_version "$document")
    
    if [[ -z "$current_version" ]]; then
        echo "❌ No version information found in document"
        return 1
    fi
    
    echo "Current Version: $current_version"
    
    # Compare versions
    local comparison=$(compare_versions "$current_version" "$new_version")
    
    if [[ "$comparison" == "equal" ]]; then
        echo "⚠️  New version same as current version"
        return 0
    elif [[ "$comparison" == "greater" ]]; then
        echo "❌ New version is older than current version"
        return 1
    fi
    
    # Determine version type
    local version_type=$(determine_version_type "$current_version" "$new_version")
    
    echo "Version Type: $version_type"
    
    # Create version update record
    local timestamp=$(date +%Y-%m-%d_%H%M%S)
    local update_record="$VERSIONS_DIR/update_${timestamp}.md"
    
    cat > "$update_record" << EOF
# Version Update: $document

**Status**: Pending ⏳
**Document**: $document
**Current Version**: $current_version
**New Version**: $new_version
**Update Type**: $version_type
**Timestamp**: $(date)

## Version Details

### Version Comparison
- Current: $current_version
- New: $new_version
- Type: $version_type
- Change: $current_version → $new_version

### Semantic Versioning
- **Major**: $(echo "$new_version" | cut -d'.' -f1)
- **Minor**: $(echo "$new_version" | cut -d'.' -f2)
- **Patch**: $(echo "$new_version" | cut -d'.' -f3)

## Update Process

### Pre-Update Checklist
- [ ] Verify approval status
- [ ] Confirm impact assessment completed
- [ ] Validate testing results
- [ ] Backup current document
- [ ] Notify affected systems

### Update Execution
- [ ] Update version in document
- [ ] Modify version references
- [ ] Update dependency versions
- [ ] Validate version format
- [ ] Confirm version compatibility

### Post-Update Checklist
- [ ] Verify version update applied
- [ ] Confirm system functionality
- [ ] Update documentation
- [ ] Notify stakeholders
- [ ] Archive update records

## Update Commands

To apply this update:
```bash
.vibe/workflows/version_updates.sh bump $document $version_type
```

---

*Version update record generated by AI Council workflow automation system*
EOF

    echo "✅ Version update planned"
    echo "📄 Update record: $update_record"
    echo ""
    echo "📋 Next Steps:"
    echo "1. Review version update"
    echo "2. Execute automated tests"
    echo "3. Apply version update"
    echo "4. Verify update success"
    
    return 0
}

# Bump version
bump_version() {
    local document="$1"
    local version_type="$2"  # patch, minor, major
    
    if [[ -z "$document" || -z "$version_type" ]]; then
        echo "Error: Document and version type required"
        echo "Usage: $0 bump <document> <version_type>"
        echo "Version types: patch, minor, major"
        return 1
    fi
    
    echo "Bumping version for: $document"
    echo "Version Type: $version_type"
    echo ""
    
    # Check if document exists
    if [[ ! -f "$document" ]]; then
        echo "❌ Document not found: $document"
        return 1
    fi
    
    # Extract current version
    local current_version=$(extract_version "$document")
    
    if [[ -z "$current_version" ]]; then
        echo "❌ No version information found in document"
        return 1
    fi
    
    echo "Current Version: $current_version"
    
    # Calculate new version
    local new_version=$(calculate_new_version "$current_version" "$version_type")
    
    echo "New Version: $new_version"
    
    # Create version bump record
    local timestamp=$(date +%Y-%m-%d_%H%M%S)
    local bump_record="$VERSIONS_DIR/bump_${timestamp}.md"
    
    cat > "$bump_record" << EOF
# Version Bump: $document

**Status**: Completed ✅
**Document**: $document
**Current Version**: $current_version
**New Version**: $new_version
**Bump Type**: $version_type
**Timestamp**: $(date)

## Version Bump Details

### Version Information
- **Document**: $document
- **Current Version**: $current_version
- **New Version**: $new_version
- **Bump Type**: $version_type

### Semantic Versioning
